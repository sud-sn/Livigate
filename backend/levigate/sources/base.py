"""Source profiles: how one client's warehouse maps onto Levigate's canonical relations.

Levigate's queries and rules are written once, against seven canonical relations (``CANONICAL_RELATIONS``). A
client's Snowflake keeps the same facts in its own shape — normalised PMS tables, Talend landing tables, BI views.
A *source profile* defines each canonical relation as a SQL query over that client's tables. At query time the
connector puts only the definitions a query needs in front of it as ``WITH`` clauses, so nothing is ever created or
written in the client's database.

Profiles are code: reviewed in a pull request like any other change, never edited from the UI and never generated by
a model. That keeps "no free-form SQL reaches a client database" true for mappings too.

A profile can also:
* point a relation (or one column) at a view the client already has, reusing the logic their BI is built on;
* carry ``quality_checks`` that run against the raw tables (duplicates, soft deletes, orphans, …);
* name the client's BI views for the parity report, which compares Levigate's numbers with the BI's.
"""

