@dataclass(frozen=True)
class QualityCheck:
    """A data-contract check. ``sql`` returns one row with a column ``N`` (how many records are affected)."""

    key: str
    title: str
    severity: str
    sql: str
    explanation: str


@dataclass(frozen=True)
class SourceProfile:
    name: str
    title: str
    description: str
    # canonical relation -> SQL over the client's tables (absent = the warehouse holds the relation under that name)
    relations: dict[str, str] = field(default_factory=dict)
    # helper definitions the relations share (names must start with SRC_ or BI_)
    helpers: dict[str, str] = field(default_factory=dict)
    # canonical relation -> the client tables/views it reads (documentation for admins)
    source_tables: dict[str, tuple[str, ...]] = field(default_factory=dict)
    quality_checks: tuple[QualityCheck, ...] = ()
    # BI relations for the parity report (BI_CLAIM_STATUS, BI_PRESCRIBER_MONTHLY), defined in ``helpers``
    parity: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()

    def definitions(self) -> dict[str, str]:
        return {**self.helpers, **self.relations}


_NAME = re.compile(r"\b([A-Z][A-Z0-9_]+)\b")


def _references(sql: str, names: set[str]) -> list[str]:
    seen: list[str] = []
    for m in _NAME.finditer(sql):
        name = m.group(1)
        if name in names and name not in seen:
            seen.append(name)
    return seen


def compose(sql: str, profile: SourceProfile, *, materialize: bool = False) -> str:
    """Prefix ``sql`` with the profile definitions it references (dependencies first) as CTEs.

    ``materialize`` adds SQLite's ``AS MATERIALIZED`` hint (dev and test engine only) so a mapped relation is computed
    once instead of being re-expanded per row; the SQL sent to Snowflake never carries it."""
    defs = profile.definitions()
    if not defs:
        return sql
    names = set(defs)
    ordered: list[str] = []
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in ordered:
            return
        if name in visiting:
            raise ValueError(f"profile '{profile.name}': circular definition through {name}")
        visiting.add(name)
        for dep in _references(defs[name], names - {name}):
            visit(dep)
        visiting.discard(name)
        ordered.append(name)

    for name in _references(sql, names):
        visit(name)
    if not ordered:
        return sql
    keyword = "AS MATERIALIZED" if materialize else "AS"
    ctes = ",\n".join(f"{n} {keyword} (\n{defs[n].strip()}\n)" for n in ordered)
    body = sql.strip()
    if body[:5].upper() == "WITH ":
        return f"WITH {ctes},\n{body[5:]}"
    return f"WITH {ctes}\n{body}"


