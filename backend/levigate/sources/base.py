def _vocabulary_check(relation: str, column: str, allowed: tuple[str | None, ...]) -> QualityCheck:
    values = ", ".join("'" + v.replace("'", "''") + "'" for v in allowed if v is not None)
    null_ok = None in allowed
    condition = f"{column} NOT IN ({values})" + ("" if null_ok else f" OR {column} IS NULL")
    return QualityCheck(
        f"vocabulary_{relation}_{column}".lower(),
        f"{relation}.{column} values Levigate does not know",
        "error",
        f"SELECT COUNT(*) AS N FROM {relation} WHERE {condition}",  # noqa: S608 - constants only
        "The mapping must translate the client's codes into Levigate's values; unknown values are treated as "
        "missing by the rules. Add the code to the mapping's translation.",
    )


CANONICAL_CHECKS = CANONICAL_CHECKS + tuple(_vocabulary_check(r, c, v) for (r, c), v in VOCABULARY.items())
